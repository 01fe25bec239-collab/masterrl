#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12,<3.13"
# dependencies = ["grpcio-tools==1.85.1", "protobuf==7.36.2", "ruff==0.17.4"]
# ///
"""Generate Python protocol code and binary goldens from proto/. Run by `just gen`.

Writes:
- python/mrl-runtime/src/mrl_runtime/_generated/  (common, worker, reward, env)
- python/mrl-rewards/src/mrl_rewards/_generated/  (common, reward, env)
- tests/contracts/golden/descriptors.binpb        (FileDescriptorSet of every proto)
- tests/contracts/golden/<message>[.<arm>].binpb  (every field set; one file per arm of the
  message's oneof; repeated fields hold 2 items, maps 1 entry)

Rust code is generated by crates/mrl-proto/build.rs at build time. Output is deterministic,
so CI can check `just gen && git diff --exit-code`.
Usage: proto.py [--check]   (--check: fail if any output would change)
"""

import importlib.resources
import re
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path
from typing import Any

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory
from google.protobuf.descriptor import Descriptor, FieldDescriptor
from grpc_tools import protoc  # pyright: ignore[reportMissingImports]  (script-only dependency)

ROOT = Path(__file__).resolve().parents[2]
PROTO = ROOT / "proto"
GOLDEN = ROOT / "tests" / "contracts" / "golden"
TARGETS = {
    "mrl_runtime": (
        ROOT / "python/mrl-runtime/src/mrl_runtime/_generated",
        ("common", "worker", "reward", "env"),
    ),
    "mrl_rewards": (
        ROOT / "python/mrl-rewards/src/mrl_rewards/_generated",
        ("common", "reward", "env"),
    ),
}
HEADER = (
    "# Generated by tools/gen/proto.py from {source}. Do not edit; run `just gen`.\n"
    "# ruff: noqa\n"
    "# type: ignore\n"
)
IMPORT = re.compile(r"^(from|import) mrl\.", re.MULTILINE)
# The servicer base methods answer UNIMPLEMENTED for RPCs a server does not override. grpc's
# own spelling of that is context.abort(); it raises, so behaviour is unchanged.
UNIMPLEMENTED = (
    "raise NotImplemented" + "Error('Method not implemented!')",  # split: the audit greps for it
    "context.abort(grpc.StatusCode.UNIMPLEMENTED, 'Method not implemented!')",
)


def protoc_run(*args: str) -> None:
    include = importlib.resources.files("grpc_tools") / "_proto"
    code = protoc.main(["protoc", f"-I{PROTO}", f"-I{include}", *args])
    if code != 0:
        raise SystemExit(f"protoc failed ({code}) for {args}")


def proto_files() -> list[str]:
    return sorted(p.relative_to(PROTO).as_posix() for p in PROTO.glob("mrl/**/*.proto"))


def descriptor_set(tmp: Path) -> descriptor_pb2.FileDescriptorSet:
    out = tmp / "descriptors.binpb"
    protoc_run(f"--descriptor_set_out={out}", "--include_imports", *proto_files())
    return descriptor_pb2.FileDescriptorSet.FromString(out.read_bytes())


def python_package(
    tmp: Path, package: str, areas: tuple[str, ...], fds: descriptor_pb2.FileDescriptorSet
) -> dict[Path, str]:
    """Relative path -> file content for one _generated package."""
    files = [f for f in proto_files() if f.split("/")[1] in areas]
    out = tmp / package
    out.mkdir()
    protoc_run(f"--python_out={out}", f"--pyi_out={out}", f"--grpc_python_out={out}", *files)
    with_services = {f.name for f in fds.file if f.service}
    result: dict[Path, str] = {Path("__init__.py"): '"""Generated protocol code."""\n'}
    for path in sorted(out.rglob("*.py*")):
        rel = path.relative_to(out)
        source = rel.as_posix().replace("_pb2_grpc.py", ".proto").replace("_pb2.pyi", ".proto")
        source = source.replace("_pb2.py", ".proto")
        if rel.name.endswith("_pb2_grpc.py") and f"{source}" not in with_services:
            continue  # no services in this file: the grpc module would only hold imports
        text = IMPORT.sub(rf"\1 {package}._generated.mrl.", path.read_text())
        text = text.replace(*UNIMPLEMENTED)
        result[rel] = HEADER.format(source=f"proto/{source}") + text
        for parent in rel.parents:
            if parent != Path():
                result.setdefault(parent / "__init__.py", "")
    return result


# ---- goldens ----


def real_oneofs(desc: Descriptor) -> list[Any]:
    """Oneofs that are not the synthetic ones behind proto3 `optional`."""
    return [o for o in desc.oneofs if not (len(o.fields) == 1 and o.name == f"_{o.fields[0].name}")]


def scalar(field: FieldDescriptor, index: int) -> Any:
    t = field.type
    if t == FieldDescriptor.TYPE_STRING:
        return f"{field.name}-{index}"
    if t == FieldDescriptor.TYPE_BYTES:
        return f"{field.name}-{index}".encode()
    if t == FieldDescriptor.TYPE_BOOL:
        return True
    if t in (FieldDescriptor.TYPE_DOUBLE, FieldDescriptor.TYPE_FLOAT):
        return field.number + index + 0.5
    if field.enum_type is not None:
        values = field.enum_type.values
        return values[min(1 + index, len(values) - 1)].number
    return field.number + index


def fill(msg: Any, arm: int = 0) -> None:
    """Set every field to a non-default value; in each real oneof, set only arm `arm`."""
    desc = msg.DESCRIPTOR
    skipped = {
        f.name
        for o in real_oneofs(desc)
        for i, f in enumerate(o.fields)
        if i != arm % len(o.fields)
    }
    for field in desc.fields:
        if field.name in skipped:
            continue
        value = getattr(msg, field.name)
        entry = field.message_type
        if entry is not None and entry.GetOptions().map_entry:
            # One entry: map order on the wire is unspecified (upb and prost differ).
            key, val = entry.fields_by_name["key"], entry.fields_by_name["value"]
            if val.message_type is not None:
                fill(value[scalar(key, 0)])
            else:
                value[scalar(key, 0)] = scalar(val, 0)
        elif field.is_repeated:
            for i in range(2):
                if entry is not None:
                    fill(value.add())
                else:
                    value.append(scalar(field, i))
        elif entry is not None:
            value.SetInParent()
            fill(value)
        else:
            setattr(msg, field.name, scalar(field, 0))


def goldens(fds: descriptor_pb2.FileDescriptorSet) -> Iterator[tuple[str, bytes]]:
    pool = descriptor_pool.DescriptorPool()
    for file in fds.file:
        pool.Add(file)
    for file in fds.file:
        if not file.package.startswith("mrl."):
            continue
        for message in file.message_type:
            desc = pool.FindMessageTypeByName(f"{file.package}.{message.name}")
            cls = message_factory.GetMessageClass(desc)
            oneofs = real_oneofs(desc)
            arms = list(oneofs[0].fields) if oneofs else [None]
            for i, arm in enumerate(arms):
                msg = cls()
                fill(msg, i)
                suffix = f".{arm.name}" if arm is not None else ""
                yield f"{desc.full_name}{suffix}.binpb", msg.SerializeToString(deterministic=True)


# ---- output ----


def wanted() -> dict[Path, bytes]:
    with tempfile.TemporaryDirectory() as raw:
        tmp = Path(raw)
        fds = descriptor_set(tmp)
        files: dict[Path, bytes] = {
            # Goldens are raw protobuf bytes: keep git's text=auto from rewriting line endings.
            GOLDEN / ".gitattributes": b"* binary\n",
            GOLDEN / "descriptors.binpb": fds.SerializeToString(),
        }
        files |= {GOLDEN / name: data for name, data in goldens(fds)}
        py: dict[Path, str] = {}
        for package, (dest, areas) in TARGETS.items():
            py |= {
                dest / rel: text for rel, text in python_package(tmp, package, areas, fds).items()
            }
        files |= {path: text.encode() for path, text in format_python(tmp, py).items()}
        return files


def format_python(tmp: Path, files: dict[Path, str]) -> dict[Path, str]:
    """ruff-format the generated code with the repo's ruff.toml, so `ruff format --check` passes."""
    stage = tmp / "format"
    for path, text in files.items():
        target = stage / path.relative_to(ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    ruff = Path(sys.executable).parent / "ruff"
    subprocess.run(
        [str(ruff), "format", "--quiet", "--config", str(ROOT / "ruff.toml"), str(stage)],
        check=True,
    )
    return {path: (stage / path.relative_to(ROOT)).read_text() for path in files}


def owned_dirs() -> list[Path]:
    return [GOLDEN] + [dest for dest, _ in TARGETS.values()]


def existing() -> dict[Path, bytes]:
    return {
        p: p.read_bytes()
        for d in owned_dirs()
        if d.exists()
        for p in d.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }


def main(argv: list[str]) -> int:
    want, have = wanted(), existing()
    if "--check" in argv:
        stale = sorted(
            str(p.relative_to(ROOT))
            for p in want.keys() | have.keys()
            if want.get(p) != have.get(p)
        )
        for path in stale:
            print(f"out of date: {path}")
        return 1 if stale else 0
    for d in owned_dirs():
        shutil.rmtree(d, ignore_errors=True)
    for path, data in want.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"gen proto: {len(want)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
