// Turns an OpenAPI 3.1 spec into one typed client module:
//   types from openapi-typescript + `createMrlClient`, bound to the thin runtime in src/runtime.
//
//   node scripts/generate.ts [--input <spec>] [--out <file>] [--check]
//
// Defaults: --input ../../openapi/mrl-api-v1.yaml, --out src/generated/mrl-api-v1.ts.
// --check exits 1 when the output file is missing or out of date (for `just gen` / CI).

import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtimeEntry = path.join(packageDir, 'src/runtime/client.ts');

export interface GenerateOptions {
  input: string;
  out: string;
}

/** Import specifier from `out` to the runtime, without extension (bundler resolution). */
function runtimeSpecifier(out: string): string {
  const rel = path
    .relative(path.dirname(out), runtimeEntry)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/** The generated module's source text. */
export async function render({ input, out }: GenerateOptions): Promise<string> {
  const ast = await openapiTS(pathToFileURL(path.resolve(input)), {
    alphabetize: true,
    silent: true,
  });
  const source = [
    `// @generated by packages/api-client/scripts/generate.ts from ${path.basename(input)}. Do not edit.`,
    `import { createTypedClient, type ClientOptions, type TypedClient } from '${runtimeSpecifier(out)}';`,
    '',
    astToString(ast),
    '/** Typed client for this spec. Paths, params, bodies and replies are checked by TypeScript. */',
    'export type MrlApiClient = TypedClient<paths>;',
    '',
    'export function createMrlClient(options: ClientOptions): MrlApiClient {',
    '  return createTypedClient<paths>(options);',
    '}',
    '',
  ].join('\n');
  const config = (await prettier.resolveConfig(out)) ?? {};
  return prettier.format(source, { ...config, parser: 'typescript' });
}

/** Writes the module; with `check`, only compares. Returns false when `check` finds a difference. */
export async function generate(options: GenerateOptions & { check?: boolean }): Promise<boolean> {
  const next = await render(options);
  if (options.check) {
    const current = await readFile(options.out, 'utf8').catch(() => null);
    return current === next;
  }
  await mkdir(path.dirname(options.out), { recursive: true });
  await writeFile(options.out, next);
  return true;
}

function arg(argv: string[], name: string): string | undefined {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
}

if (import.meta.main) {
  const argv = process.argv.slice(2);
  const input = arg(argv, '--input') ?? path.join(packageDir, '../../openapi/mrl-api-v1.yaml');
  const out = arg(argv, '--out') ?? path.join(packageDir, 'src/generated/mrl-api-v1.ts');
  const check = argv.includes('--check');
  try {
    const ok = await generate({ input, out, check });
    if (!ok) {
      console.error(`${out} is out of date. Run: node packages/api-client/scripts/generate.ts`);
      process.exit(1);
    }
    console.log(check ? `${out} is up to date.` : `Wrote ${out}`);
  } catch (err) {
    console.error(
      `Could not generate the API client from ${input}: ${err instanceof Error ? err.message : String(err)}`,
    );
    process.exit(1);
  }
}
