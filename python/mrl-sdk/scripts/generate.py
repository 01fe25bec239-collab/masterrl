"""Generate `mrl_sdk._generated` from the server's OpenAPI document.

    uv run python python/mrl-sdk/scripts/generate.py           # write the files
    uv run python python/mrl-sdk/scripts/generate.py --check   # exit 1 when they are stale

Writes `models.py` (one TypedDict per schema) and `operations.py` (every operation's method,
path and parameters). The hand-written client in `mrl_sdk.client` uses both.
"""

from __future__ import annotations

import argparse
import keyword
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / "openapi" / "mrl-api-v1.yaml"
OUT = ROOT / "python" / "mrl-sdk" / "src" / "mrl_sdk" / "_generated"
HEADER = (
    '"""@generated by python/mrl-sdk/scripts/generate.py from openapi/mrl-api-v1.yaml.'
    ' Do not edit."""\n'
)
PAGE_PREFIX = "Page_"
# Characters ruff flags as look-alikes in docstrings.
PLAIN = str.maketrans({"\u2212": "-", "\u2013": "-", "\u2014": "-", "\u2019": "'"})


def doc(text: str | None, indent: str) -> list[str]:
    """A one-line docstring (first line of `text`), or nothing."""
    if not text:
        return []
    first = text.strip().splitlines()[0].translate(PLAIN)
    first = first.replace("\\", "\\\\").replace('"""', "'''")
    if first.endswith('"'):
        first += " "
    return [f'{indent}"""{first}"""']


def class_name(schema: str) -> str:
    """The Python name of a schema: `Page_Run` becomes `RunPage`."""
    if schema.startswith(PAGE_PREFIX):
        return schema.removeprefix(PAGE_PREFIX) + "Page"
    return schema


def py_type(schema: dict[str, Any], names: set[str]) -> str:
    """The Python annotation for a JSON Schema."""
    if "$ref" in schema:
        return class_name(schema["$ref"].rsplit("/", 1)[-1])
    kinds = schema.get("type", "object")
    kinds = kinds if isinstance(kinds, list) else [kinds]
    nullable = "null" in kinds
    kinds = [k for k in kinds if k != "null"]
    base = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "object": "dict[str, Any]",
    }
    if "enum" in schema:
        text = "Literal[" + ", ".join(f'"{v}"' for v in schema["enum"]) + "]"
    elif kinds == ["array"]:
        text = f"list[{py_type(schema.get('items', {}), names)}]"
    else:
        text = " | ".join(base.get(k, "Any") for k in kinds) or "Any"
    return f"{text} | None" if nullable else text


def flattened(s: dict[str, Any], schemas: dict[str, Any]) -> dict[str, Any]:
    """`s` with every `allOf` part (a `$ref` or an inline object) merged into one object."""
    if "allOf" not in s:
        return s
    props: dict[str, Any] = dict(s.get("properties", {}))
    required: list[str] = list(s.get("required", []))
    for part in s["allOf"]:
        ref = part.get("$ref", "")
        piece = flattened(schemas[ref.rsplit("/", 1)[-1]], schemas) if ref else part
        props.update(piece.get("properties", {}))
        required += [r for r in piece.get("required", []) if r not in required]
    return {**s, "properties": props, "required": required}


def models(spec: dict[str, Any]) -> str:
    """Source of `models.py`."""
    schemas: dict[str, Any] = spec["components"]["schemas"]
    names = set(schemas)
    lines = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, NotRequired, TypedDict",
        "",
    ]
    exported: list[str] = []
    for name in sorted(schemas, key=class_name):
        s = flattened(schemas[name], schemas)
        exported.append(class_name(name))
        if "enum" in s:
            lines += ["", f"{name} = {py_type(s, names)}", *doc(s.get("description"), "")]
            continue
        if "oneOf" in s or "anyOf" in s:
            # A choice of shapes: no single TypedDict describes it.
            lines += ["", f"{class_name(name)} = dict[str, Any]", *doc(s.get("description"), "")]
            continue
        lines += ["", "", f"class {class_name(name)}(TypedDict):"]
        lines += doc(s.get("description"), "    ")
        props: dict[str, Any] = s.get("properties", {})
        required = set(s.get("required", []))
        if not props:
            if not lines[-1].endswith('"""'):
                lines.append("    pass")
            continue
        if lines[-1].endswith('"""'):
            lines.append("")
        for i, (field, fs) in enumerate(sorted(props.items())):
            item = name.removeprefix(PAGE_PREFIX)
            if name.startswith(PAGE_PREFIX) and field == "items" and item in names:
                t = f"list[{item}]"
            else:
                t = py_type(fs, names)
            t = t if field in required else f"NotRequired[{t}]"
            key = f"{field}_" if keyword.iskeyword(field) else field
            if i:
                lines.append("")
            lines.append(f"    {key}: {t}")
            lines += doc(fs.get("description"), "    ")
    lines += ["", "", "__all__ = ["] + [f'    "{n}",' for n in sorted(exported)] + ["]", ""]
    return "\n".join(lines)


def operations(spec: dict[str, Any]) -> str:
    """Source of `operations.py`."""
    lines = [
        HEADER,
        "from typing import NamedTuple",
        "",
        "",
        "class Operation(NamedTuple):",
        '    """One API operation."""',
        "",
        "    method: str",
        '    """HTTP method."""',
        "",
        "    path: str",
        '    """Path under the server address, with `{name}` placeholders."""',
        "",
        "    path_params: tuple[str, ...]",
        '    """Placeholders in `path`."""',
        "",
        "    query_params: tuple[str, ...]",
        '    """Accepted query parameters."""',
        "",
        "    headers: tuple[str, ...]",
        '    """Required request headers."""',
        "",
        "    has_body: bool",
        '    """True if the operation takes a JSON body."""',
        "",
        "",
        "OPERATIONS: dict[str, Operation] = {",
    ]
    ops: list[tuple[str, str, str, dict[str, Any]]] = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            ops.append((op["operationId"], method.upper(), path, op))
    for op_id, method, path, op in sorted(ops):
        params = op.get("parameters", [])

        def names(where: str, params: list[dict[str, Any]] = params) -> str:
            found = [p["name"] for p in params if p["in"] == where]
            return "(" + "".join(f'"{n}", ' for n in found).rstrip(" ") + ")"

        lines += [
            f'    "{op_id}": Operation(',
            f'        "{method}",',
            f'        "{path}",',
            f"        {names('path')},",
            f"        {names('query')},",
            f"        {names('header')},",
            f"        {'requestBody' in op},",
            "    ),",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def formatted(source: str) -> str:
    """`source` after `ruff format`, so the files match the repo's style exactly."""
    done = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "generated.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
        cwd=ROOT,
    )
    return done.stdout


def render() -> dict[str, str]:
    """Every generated file, by name."""
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    init = HEADER + "\nfrom mrl_sdk._generated.operations import OPERATIONS, Operation\n\n"
    init += '__all__ = ["OPERATIONS", "Operation"]\n'
    files = {"__init__.py": init, "models.py": models(spec), "operations.py": operations(spec)}
    return {name: formatted(text) for name, text in files.items()}


def stale() -> list[str]:
    """Files whose content differs from what the spec produces."""
    out = []
    for name, text in render().items():
        path = OUT / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            out.append(name)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the files are stale")
    args = parser.parse_args()
    if args.check:
        bad = stale()
        if bad:
            print(f"stale: {', '.join(bad)}; run python/mrl-sdk/scripts/generate.py")
            return 1
        print("mrl-sdk: generated files are current")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"mrl-sdk: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
