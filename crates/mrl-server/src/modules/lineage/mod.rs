#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn node_ids_round_trip() {
        let id = mrl_domain::ids::RunId::new();
        let n = NodeRef::parse(&id.to_string()).unwrap();
        assert_eq!(n.kind, "run");
        assert_eq!(n.id, id.as_uuid());
        assert_eq!(n.to_string(), id.to_string());
        for bad in [
            "",
            "run",
            "nope_01JD8X3F4G5H6J7K8M9N0PQRST",
            "run_short",
            "run_",
        ] {
            assert!(NodeRef::parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn upstream_ends() {
        // run trained_on dsv: the dataset came first. run produced ckpt: the run came first.
        assert!(Relation::TrainedOn.upstream_is_to());
        assert!(Relation::DerivedFrom.upstream_is_to());
        assert!(!Relation::Produced.upstream_is_to());
        assert!(!Relation::PromotedTo.upstream_is_to());
        assert!(!Relation::EvaluatedBy.upstream_is_to());
        for r in Relation::ALL {
            assert_eq!(relation_of(r.as_str()), Some(r));
        }
    }

    #[test]
    fn relations_round_trip() {
        for r in [
            Relation::DerivedFrom,
            Relation::GeneratedBy,
            Relation::TrainedOn,
        ] {
            assert_eq!(relation_of(r.as_str()), Some(r));
        }
        assert_eq!(relation_of("bogus"), None);
    }
}
