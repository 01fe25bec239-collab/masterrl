#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn node_ids_round_trip() {
        let id = mrl_domain::ids::RunId::new();
        let n = NodeRef::parse(&id.to_string()).unwrap();
        assert_eq!(n.kind, "run");
        assert_eq!(n.id, id.as_uuid());
        assert_eq!(n.to_string(), id.to_string());
        for bad in [
            "",
            "run",
            "nope_01JD8X3F4G5H6J7K8M9N0PQRST",
            "run_short",
            "run_",
        ] {
            assert!(NodeRef::parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn relations_round_trip() {
        for r in [
            Relation::DerivedFrom,
            Relation::GeneratedBy,
            Relation::TrainedOn,
        ] {
            assert_eq!(relation_of(r.as_str()), Some(r));
        }
        assert_eq!(relation_of("bogus"), None);
    }
}
