//! Lineage (P19): edges between any two entities, written by the modules that create them
//! and read as a graph with authorization filtering.
//!
//! An edge reads "from `relation` to", like `run trained_on dsv` or `art derived_from ckpt`.
//! Nodes are typed ids (`run_…`, `dsv_…`, `art_…`); their prefix is the kind.
//!
//! Writing (inside the transaction that creates the entity; only link entities of `org`,
//! which the writing module has checked):
//! ```text
//! LineageWriter::link(tx, org, NodeRef::parse("run_…")?, Relation::TrainedOn, dsv).await?;
//! ```
//! Callers of `POST /artifacts` may link only to artifacts and uploads (checked here).
//!
//! Reading: `GET /api/v1/lineage/{id}?direction=up|down|both&depth=1..10` (`upstream` and
//! `downstream` also work). Each relation says which end it depends on
//! ([`Relation::upstream_is_to`]): `run trained_on dsv` makes the dataset upstream of the
//! run, `run produced ckpt` makes the run upstream of the checkpoint. `up` follows
//! dependencies, `down` what was made from the node; edges are returned as stored. Every node
//! is checked exactly as its owner's GET checks it: P19's kinds (artifacts, uploads, secrets)
//! here, other kinds through a [`NodeLookup`](crate::modules::artifacts::NodeLookup) their
//! module registers. A node the caller may not see, or that nobody can resolve, is returned
//! as `{"id": "hidden-N", "kind": null, "redacted": true}` and is not followed further; such
//! a root is not found.

use crate::app::AppState;
use crate::db::{DbError, Tx};
use crate::error::{ApiError, ErrorCode};
use crate::modules::artifacts::{field, org_of, owned, ArtifactStore, Error, READ};
use crate::seams::{Decision, RequestContext, Resource};
use axum::extract::{Path, Query, State};
use axum::{Extension, Json};
use mrl_domain::ids::{decode_base32, encode_base32, PREFIXES};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use std::sync::Arc;
use uuid::Uuid;

/// Longest walk.
pub const MAX_DEPTH: u32 = 10;
/// Most edges in one answer; the walk stops there and sets `truncated`.
pub const MAX_EDGES: usize = 1000;

/// How two entities are related (Doc 09 §3.10).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, utoipa::ToSchema)]
#[serde(rename_all = "snake_case")]
pub enum Relation {
    /// Made from (a checkpoint from a run, a dataset version from another).
    DerivedFrom,
    /// A run trained on a dataset version or model.
    TrainedOn,
    /// A run used a reward version.
    RewardedBy,
    /// A run produced a checkpoint or artifact.
    Produced,
    /// A checkpoint was promoted to a model version.
    PromotedTo,
    /// A model version was deployed.
    DeployedAs,
    /// Evaluated by an evaluation.
    EvaluatedBy,
    /// Exported as an export artifact.
    ExportedAs,
    /// A dataset version labelled from feedback.
    LabelledFrom,
    /// Generated by a model or run.
    GeneratedBy,
}

impl Relation {
    /// Every relation.
    pub const ALL: [Relation; 10] = [
        Self::DerivedFrom,
        Self::TrainedOn,
        Self::RewardedBy,
        Self::Produced,
        Self::PromotedTo,
        Self::DeployedAs,
        Self::EvaluatedBy,
        Self::ExportedAs,
        Self::LabelledFrom,
        Self::GeneratedBy,
    ];

    /// True when `from relation to` means `from` depends on `to` (`to` is upstream): made
    /// from, trained on, rewarded by, labelled from, generated by. False when `to` came out
    /// of `from` (`from` is upstream): produced, promoted to, deployed as, evaluated by,
    /// exported as.
    pub fn upstream_is_to(self) -> bool {
        matches!(
            self,
            Self::DerivedFrom
                | Self::TrainedOn
                | Self::RewardedBy
                | Self::LabelledFrom
                | Self::GeneratedBy
        )
    }

    /// The stored name, like `trained_on`.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::DerivedFrom => "derived_from",
            Self::TrainedOn => "trained_on",
            Self::RewardedBy => "rewarded_by",
            Self::Produced => "produced",
            Self::PromotedTo => "promoted_to",
            Self::DeployedAs => "deployed_as",
            Self::EvaluatedBy => "evaluated_by",
            Self::ExportedAs => "exported_as",
            Self::LabelledFrom => "labelled_from",
            Self::GeneratedBy => "generated_by",
        }
    }
}

/// One entity: its kind (an id prefix, like `run`) and UUID.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct NodeRef {
    /// Id prefix, like `run` or `dsv`.
    pub kind: &'static str,
    /// The UUID inside the id.
    pub id: Uuid,
}

/// Text that is not a typed id.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0:?} is not an id the app knows")]
pub struct BadNodeId(pub String);

impl NodeRef {
    /// A node of a known `kind`. Unknown kinds become `other`, which no id uses.
    pub fn new(kind: &str, id: Uuid) -> Self {
        let kind = PREFIXES
            .iter()
            .copied()
            .find(|p| *p == kind)
            .unwrap_or("other");
        Self { kind, id }
    }

    /// Reads a typed id like `run_01JD8X3F4G5H6J7K8M9N0PQRST`.
    pub fn parse(text: &str) -> Result<Self, BadNodeId> {
        let bad = || BadNodeId(text.chars().take(64).collect());
        let (prefix, rest) = text.split_once('_').ok_or_else(bad)?;
        let kind = PREFIXES
            .iter()
            .copied()
            .find(|p| *p == prefix)
            .ok_or_else(bad)?;
        let bytes = decode_base32(rest).map_err(|_| bad())?;
        Ok(Self {
            kind,
            id: Uuid::from_bytes(bytes),
        })
    }
}

impl std::fmt::Display for NodeRef {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}_{}", self.kind, encode_base32(self.id.into_bytes()))
    }
}

/// Writes lineage edges.
pub struct LineageWriter;

impl LineageWriter {
    /// Records `from relation to` in `org`, inside the caller's transaction. Writing the same
    /// edge again does nothing.
    pub async fn link(
        tx: &mut Tx,
        org: &str,
        from: NodeRef,
        relation: Relation,
        to: NodeRef,
    ) -> Result<(), DbError> {
        sqlx::query(
            "INSERT INTO lineage_edges (org_id, from_kind, from_id, relation, to_kind, to_id)
             VALUES ($1, $2, $3, $4, $5, $6) ON CONFLICT DO NOTHING",
        )
        .bind(org)
        .bind(from.kind)
        .bind(from.id)
        .bind(relation.as_str())
        .bind(to.kind)
        .bind(to.id)
        .execute(&mut **tx)
        .await?;
        Ok(())
    }
}

/// Kinds whose rows P19 owns, so it can tell whether an id is real and whose it is.
pub(crate) fn has_table(kind: &str) -> bool {
    matches!(kind, "art" | "up")
}

/// How to check the caller may see `node` of `org`: the action and resource its owner's
/// own GET checks. P19's kinds are looked up here (artifacts when committed, uploads,
/// secrets unless being deleted), others through the lookup their module registered
/// ([`ArtifactStore::add_lineage_lookup`]). `None`: not in `org`, or a kind nobody can
/// resolve; such nodes are redacted and never a root.
pub(crate) async fn access(
    store: &ArtifactStore,
    org: &str,
    node: NodeRef,
) -> Result<Option<(&'static str, Resource)>, Error> {
    let project = |sql: &'static str| async move {
        sqlx::query_scalar::<_, Option<String>>(sql)
            .bind(org)
            .bind(node.id)
            .fetch_optional(store.db().pool())
            .await
    };
    let id = node.to_string();
    Ok(match node.kind {
        "art" => project(
            "SELECT project_id FROM artifacts WHERE org_id = $1 AND id = $2 AND state = 'COMMITTED'",
        )
        .await?
        .map(|p| (READ, owned("artifact", org, id, p))),
        "up" => project("SELECT project_id FROM uploads WHERE org_id = $1 AND id = $2")
            .await?
            .map(|p| (crate::modules::uploads::ACTION, owned("upload", org, id, p))),
        "sec" => project(
            "SELECT project_id FROM secrets_metadata WHERE org_id = $1 AND id = $2 AND NOT deleting",
        )
        .await?
        .map(|p| (crate::modules::secrets::READ, owned("secret", org, id, p))),
        kind => match store.lookup(kind) {
            Some(l) => l.find(org, node.id).await?,
            None => None,
        },
    })
}

/// True when `node` may be a lineage root in `org`: its owner finds it there.
pub async fn belongs(store: &ArtifactStore, org: &str, node: NodeRef) -> Result<bool, Error> {
    Ok(access(store, org, node).await?.is_some())
}

/// The read action for a node kind.
pub fn read_action(kind: &str) -> &'static str {
    match kind {
        "run" | "job" | "att" | "exp" => "runs.read",
        "ckpt" => "checkpoints.read",
        "mdl" | "mv" => "models.read",
        "ds" | "dsv" => "datasets.read",
        "evr" => "evaluations.read",
        "rwd" | "rwdv" | "rwc" => "rewards.read",
        "dep" => "promotions.read",
        _ => "lineage.read",
    }
}

/// `GET /lineage/{id}` query.
#[derive(Debug, Clone, Default, Deserialize, utoipa::IntoParams)]
#[into_params(parameter_in = Query)]
pub struct LineageQuery {
    /// `up` (what the node came from), `down` (what came from it) or `both` (default).
    /// `upstream` and `downstream` work too.
    pub direction: Option<String>,
    /// Steps to walk, 1–10 (default 3).
    pub depth: Option<String>,
}

/// A node in the answer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, utoipa::ToSchema)]
pub struct Node {
    /// The typed id, or `hidden-N` for a node the caller may not see.
    pub id: String,
    /// Kind (id prefix); `null` when redacted.
    pub kind: Option<String>,
    /// True when the caller may not see this node.
    pub redacted: bool,
}

/// An edge in the answer; `from` and `to` are node ids from `nodes`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, utoipa::ToSchema)]
pub struct Edge {
    /// Source node id.
    pub from: String,
    /// Relation.
    pub relation: Relation,
    /// Target node id.
    pub to: String,
}

/// A lineage graph around one node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, utoipa::ToSchema)]
pub struct Graph {
    /// The node asked about.
    pub root: String,
    /// Every node reached.
    pub nodes: Vec<Node>,
    /// Every edge between them.
    pub edges: Vec<Edge>,
    /// True when the walk stopped at the edge limit (1000).
    pub truncated: bool,
}

#[derive(sqlx::FromRow)]
struct EdgeRow {
    from_kind: String,
    from_id: Uuid,
    relation: String,
    to_kind: String,
    to_id: Uuid,
}

fn relation_of(s: &str) -> Option<Relation> {
    serde_json::from_value(serde_json::Value::String(s.to_owned())).ok()
}

/// Reads the lineage graph around a node.
#[utoipa::path(get, path = "/lineage/{id}", tag = "lineage", params(("id" = String, Path, description = "A typed id, like `run_…`."), LineageQuery),
    responses((status = 200, body = Graph), (status = 404, body = crate::error::Problem)))]
pub(crate) async fn query(
    State(s): State<AppState>,
    Extension(store): Extension<Arc<ArtifactStore>>,
    ctx: RequestContext,
    Path(id): Path<String>,
    Query(q): Query<LineageQuery>,
) -> Result<Json<Graph>, Error> {
    let (up, down) = match q.direction.as_deref() {
        None | Some("both") => (true, true),
        Some("up" | "upstream") => (true, false),
        Some("down" | "downstream") => (false, true),
        Some(_) => return Err(field("/direction", "Use up, down or both.")),
    };
    let depth = match q.depth.as_deref() {
        None => 3,
        Some(d) => d
            .parse::<u32>()
            .ok()
            .filter(|d| (1..=MAX_DEPTH).contains(d))
            .ok_or_else(|| field("/depth", "Use a whole number from 1 to 10."))?,
    };
    let root = NodeRef::parse(&id)
        .map_err(|_| ApiError::new(ErrorCode::NotFound, "No item with this id exists."))?;
    let org = org_of(&ctx)?;
    s.authorize(&ctx, READ, &graph_resource(&org)).await?;
    let gone = || ApiError::new(ErrorCode::NotFound, "No item with this id exists.");
    let (action, res) = access(&store, &org, root).await?.ok_or_else(gone)?;
    s.authorize(&ctx, action, &res).await?;
    Ok(Json(
        walk(&s, &store, &ctx, &org, root, up, down, depth).await?,
    ))
}

/// The lineage graph of `org` as a whole.
fn graph_resource(org: &str) -> Resource {
    Resource {
        kind: "lineage".to_owned(),
        id: None,
        org: Some(org.to_owned()),
        project: None,
    }
}

#[allow(clippy::too_many_arguments)]
async fn walk(
    s: &AppState,
    store: &ArtifactStore,
    ctx: &RequestContext,
    org: &str,
    root: NodeRef,
    up: bool,
    down: bool,
    depth: u32,
) -> Result<Graph, Error> {
    // Every node met, as the caller sees it.
    let mut shown: HashMap<NodeRef, Node> = HashMap::new();
    shown.insert(
        root,
        Node {
            id: root.to_string(),
            kind: Some(root.kind.to_owned()),
            redacted: false,
        },
    );
    let mut order = vec![root];
    let mut edges = Vec::new();
    let mut seen_edges = HashSet::new();
    // Nodes to expand next, going up and going down; each at most once per direction. A
    // node keeps the direction it was reached in, so `both` is the two walks together.
    let mut ups: Vec<NodeRef> = if up { vec![root] } else { Vec::new() };
    let mut downs: Vec<NodeRef> = if down { vec![root] } else { Vec::new() };
    let mut expanded: HashSet<(NodeRef, bool)> = HashSet::new();
    let to_relations: Vec<&str> = Relation::ALL
        .iter()
        .filter(|r| r.upstream_is_to())
        .map(|r| r.as_str())
        .collect();
    let mut truncated = false;
    for _ in 0..depth {
        ups.retain(|n| expanded.insert((*n, true)));
        downs.retain(|n| expanded.insert((*n, false)));
        if (ups.is_empty() && downs.is_empty()) || truncated {
            break;
        }
        let set = |v: &[NodeRef]| -> (Vec<&str>, Vec<Uuid>) {
            (
                v.iter().map(|n| n.kind).collect(),
                v.iter().map(|n| n.id).collect(),
            )
        };
        let ((uk, ui), (dk, di)) = (set(&ups), set(&downs));
        // An edge's upstream end is `to` when its relation is in $6, else `from`. Going up
        // from a node means it is the edge's downstream end; going down, its upstream end.
        let rows: Vec<EdgeRow> = sqlx::query_as(
            "WITH u(kind, id) AS (SELECT * FROM unnest($2::text[], $3::uuid[])),
                  d(kind, id) AS (SELECT * FROM unnest($4::text[], $5::uuid[]))
             SELECT from_kind, from_id, relation, to_kind, to_id FROM lineage_edges e
             WHERE e.org_id = $1 AND (
                   (e.relation = ANY($6) AND (e.from_kind, e.from_id) IN (SELECT kind, id FROM u))
                OR (e.relation <> ALL($6) AND (e.to_kind, e.to_id) IN (SELECT kind, id FROM u))
                OR (e.relation = ANY($6) AND (e.to_kind, e.to_id) IN (SELECT kind, id FROM d))
                OR (e.relation <> ALL($6) AND (e.from_kind, e.from_id) IN (SELECT kind, id FROM d)))
             ORDER BY e.created_at, e.from_id, e.to_id
             LIMIT $7",
        )
        .bind(org)
        .bind(&uk)
        .bind(&ui)
        .bind(&dk)
        .bind(&di)
        .bind(&to_relations)
        .bind(i64::try_from(MAX_EDGES + 1).unwrap_or(1001))
        .fetch_all(store.db().pool())
        .await?;
        let (mut next_up, mut next_down) = (Vec::new(), Vec::new());
        for r in rows {
            let Some(relation) = relation_of(&r.relation) else {
                continue;
            };
            let (from, to) = (
                NodeRef::new(&r.from_kind, r.from_id),
                NodeRef::new(&r.to_kind, r.to_id),
            );
            if !seen_edges.insert((from, relation, to)) {
                continue;
            }
            if edges.len() >= MAX_EDGES {
                truncated = true;
                break;
            }
            let (upper, lower) = if relation.upstream_is_to() {
                (to, from)
            } else {
                (from, to)
            };
            // Which end is new, and which way it continues.
            let mut reached = Vec::new();
            if ups.contains(&lower) {
                reached.push((upper, true));
            }
            if downs.contains(&upper) {
                reached.push((lower, false));
            }
            for (n, going_up) in reached {
                let visible = match shown.get(&n) {
                    Some(node) => !node.redacted,
                    None => {
                        let visible = match access(store, org, n).await? {
                            Some((action, res)) => {
                                s.seams.authorizer.authorize(ctx, action, &res).await?
                                    == Decision::Allow
                            }
                            None => false,
                        };
                        shown.insert(
                            n,
                            if visible {
                                Node {
                                    id: n.to_string(),
                                    kind: Some(n.kind.to_owned()),
                                    redacted: false,
                                }
                            } else {
                                Node {
                                    id: format!("hidden-{}", order.len()),
                                    kind: None,
                                    redacted: true,
                                }
                            },
                        );
                        order.push(n);
                        visible
                    }
                };
                if visible {
                    if going_up {
                        next_up.push(n);
                    } else {
                        next_down.push(n);
                    }
                }
            }
            let id_of = |n: &NodeRef| shown.get(n).map(|x| x.id.clone()).unwrap_or_default();
            edges.push(Edge {
                from: id_of(&from),
                relation,
                to: id_of(&to),
            });
        }
        ups = next_up;
        downs = next_down;
    }
    Ok(Graph {
        root: root.to_string(),
        nodes: order.iter().filter_map(|n| shown.get(n).cloned()).collect(),
        edges,
        truncated,
    })
}

